#!/usr/bin/env python3
"""Generate a small, local 6x6 composition pilot (AI-assisted tooling).

Native values only select untrusted strategy hints. Agda independently checks
closed solve80 frontier entries, the outer skeletons, and their actual joint play.
This pilot starts at p26; it asserts nothing about the initial 6x6 position.
"""
from __future__ import annotations

import argparse
from functools import lru_cache
import hashlib
import json
from pathlib import Path

import generate6
import ref
import solve6

ROOT = Path(__file__).resolve().parents[1]
HEADER = generate6.HEADER


@lru_cache(maxsize=None)
def hint(state: ref.State) -> int:
    return solve6.solve(state)


def build_bound(own: int, states: list[ref.State], indices: list[int]):
    line = {state: i for i, state in enumerate(states)}
    entries: list[ref.State] = []
    seen: dict[ref.State, int] = {}

    def visit(state: ref.State):
        if state not in line and state.cells.count(ref.EMPTY) <= 4:
            if state not in seen:
                seen[state] = len(entries)
                entries.append(state)
            return ("lemma", seen[state])
        children = ref.successors(state)
        if not children:
            assert ref.score(state) >= 4 if own == ref.WHITE else ref.score(state) <= 4
            return ("leaf",)
        if not ref.placements(state):
            assert len(children) == 1
            return ("pass", visit(children[0]))
        if state.turn == own:
            if state in line:
                index = indices[line[state]]
            else:
                index = next(i for i, child in enumerate(children)
                             if (hint(child) >= 4 if own == ref.WHITE else hint(child) <= 4))
            return ("choice", index, visit(children[index]))
        return ("fork", [visit(child) for child in children])

    skeleton = visit(states[26])
    assert len(set(entries)) == len(entries)
    assert all(state not in line and state.cells.count(ref.EMPTY) <= 4 for state in entries)
    return skeleton, entries


def skeleton_text(node, split: int) -> str:
    kind = node[0]
    if kind == "leaf":
        return "local localLeaf"
    if kind == "lemma":
        index = node[1]
        return f"lemma {0 if index < split else 1} {index if index < split else index - split}"
    if kind == "choice":
        return f"choose {node[1]} ({skeleton_text(node[2], split)})"
    if kind == "pass":
        return f"passing ({skeleton_text(node[1], split)})"
    if kind == "fork":
        children = " ∷ ".join(f"({skeleton_text(child, split)})" for child in node[1])
        return f"replies ({children} ∷ [])"
    raise ValueError(kind)


def write(relative: str, content: str) -> Path:
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return path


def emit() -> dict:
    states, indices, _ = generate6.replay()
    assert states[26].cells.count(ref.EMPTY) == 6
    files: list[Path] = []
    results = {}
    skeletons = {}
    for name, own, player, goal in (("Lower", ref.WHITE, "white", "lowerGoal"),
                                    ("Upper", ref.BLACK, "black", "upperGoal")):
        tree, entries = build_bound(own, states, indices)
        split = (len(entries) + 1) // 2
        skeletons[name] = skeleton_text(tree, split)
        parts = (entries[:split], entries[split:])
        results[name.lower()] = {"entries": len(entries), "shards": list(map(len, parts)),
                                 "frontier": [generate6.encode_state(s) for s in entries]}
        for i, part in enumerate(parts):
            module = f"{name}{i}"
            encoded = "".join(generate6.encode_state(s) +
                              generate6.encode_local({"kind": "solve", "fuel": 80}) for s in part)
            files.append(write(f"src/Othello/Data6/{module}.agda", HEADER + f'''-- Untrusted compact data; generated by tools/pilot6.py (AI-assisted).
module Othello.Data6.{module} where

open import Agda.Builtin.String using (String)

encoded : String
encoded = "{encoded}"
'''))
            files.append(write(f"src/Othello/Proof6/{module}.agda", HEADER + f'''-- Each shard is checked independently; no native oracle is imported.
module Othello.Proof6.{module} where

open import Prelude
open import Game.Core using ({player})
open import Game.Composite using (Entry; shardOK)
open import Othello.Board using (State; six)
open import Othello.Encode6 using (decodeShard)
open import Othello.Fast6 using (fastGame6)
open import Othello.Statements using ({goal})
open import Othello.Data6.{module} using (encoded)

entries : List (Entry (State six))
entries = fromMaybe [] (decodeShard encoded)

decoded : decodeShard encoded ≡ just entries
decoded = refl

abstract
  accepted : shardOK fastGame6 {player} ({goal} 4) entries ≡ true
  accepted = refl
'''))

    literals = "".join(f'''p{i} : State six
p{i} = fromMaybe (initial six) (decodeState "{generate6.encode_state(states[i])}")

''' for i in range(26, 34))
    files.append(write("src/Othello/Pilot6.agda", HEADER + '''-- Local p26 pilot only; this module does not inhabit Problem2.
-- Generated by tools/pilot6.py with AI assistance.
module Othello.Pilot6 where

open import Prelude
open import Game.Core
open import Game.Composite
open import Game.Joint
open import Game.Transfer
open import Othello.Board
open import Othello.Rules using (game)
open import Othello.Fast6 using (fastGame6)
open import Othello.Encode6 using (decodeState; stateEquality6)
open import Othello.Statements using (lowerGoal; upperGoal)
open import Othello.Proof6 using (fastAgreement; terminalCounts; counts-sound)
import Othello.Proof6.Lower0 as L0
import Othello.Proof6.Lower1 as L1
import Othello.Proof6.Upper0 as U0
import Othello.Proof6.Upper1 as U1

''' + literals + f'''lowerTables upperTables : Shards (State six)
lowerTables = L0.entries ∷ L1.entries ∷ []
upperTables = U0.entries ∷ U1.entries ∷ []

lowerItems : itemsOK fastGame6 white (lowerGoal 4) lowerTables ≡ true
lowerItems = itemsOK-cons fastGame6 white (lowerGoal 4) L0.entries (L1.entries ∷ [])
  L0.accepted (itemsOK-cons fastGame6 white (lowerGoal 4) L1.entries [] L1.accepted refl)

upperItems : itemsOK fastGame6 black (upperGoal 4) upperTables ≡ true
upperItems = itemsOK-cons fastGame6 black (upperGoal 4) U0.entries (U1.entries ∷ [])
  U0.accepted (itemsOK-cons fastGame6 black (upperGoal 4) U1.entries [] U1.accepted refl)

lowerSkeleton upperSkeleton : Skeleton
lowerSkeleton = {skeletons['Lower']}
upperSkeleton = {skeletons['Upper']}

lowerRoot : checkComposite stateEquality6 lowerTables fastGame6 white (lowerGoal 4)
  p26 lowerSkeleton ≡ true
lowerRoot = refl

upperRoot : checkComposite stateEquality6 upperTables fastGame6 black (upperGoal 4)
  p26 upperSkeleton ≡ true
upperRoot = refl

lowerBound : WhiteGuarantees (game six) (lowerGoal 4) p26
lowerBound = guarantees-transfer fastGame6 (game six) fastAgreement
  (compositionSound stateEquality6 lowerTables fastGame6 white (lowerGoal 4)
    p26 lowerSkeleton lowerItems lowerRoot)

upperBound : BlackGuarantees (game six) (upperGoal 4) p26
upperBound = guarantees-transfer fastGame6 (game six) fastAgreement
  (compositionSound stateEquality6 upperTables fastGame6 black (upperGoal 4)
    p26 upperSkeleton upperItems upperRoot)

suffix : List (State six)
suffix = p27 ∷ p28 ∷ p29 ∷ p30 ∷ p31 ∷ p32 ∷ p33 ∷ []

jointOK : jointCheck stateEquality6 fastGame6 terminalCounts p26
  (forcing lowerBound) (forcing upperBound) suffix ≡ true
jointOK = refl

record LocalValue : Set where
  field
    lower : WhiteGuarantees (game six) (lowerGoal 4) p26
    upper : BlackGuarantees (game six) (upperGoal 4) p26
open LocalValue public

optimal : LocalValue
optimal = record {{ lower = lowerBound ; upper = upperBound }}

completedOptimalPair : Σ (State six) (λ t →
  CompletedPlay (game six) white (forcing (lower optimal))
    (forcing (upper optimal)) p26 t ×
  ((discs black t ≡ 16) × (discs white t ≡ 20)))
completedOptimalPair with joint-sound stateEquality6 fastGame6 terminalCounts p26
  (forcing lowerBound) (forcing upperBound) suffix jointOK
... | t , play , countOK = t ,
  completedPlay-transfer fastGame6 (game six) fastAgreement play , counts-sound t countOK
'''))
    return {"format": "othello-local-pilot6-v1", "start": "p26", "value": 4,
            "cutoff_occupied": 32, "fuel": 80, **results,
            "files_sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                              for p in files},
            "trust": "untrusted generation; only Agda acceptance proves the local result"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    print(json.dumps(emit(), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
